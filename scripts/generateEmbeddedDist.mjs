import fs from 'node:fs';
import path from 'node:path';

const distDir = path.resolve(process.cwd(), 'dist');
const outputFile = path.resolve(process.cwd(), 'src', 'embeddedDist.ts');

if (!fs.existsSync(distDir)) {
  console.error('[generateEmbeddedDist] dist folder not found. Run vite build first.');
  process.exit(1);
}

function getContentType(filePath) {
  const ext = path.extname(filePath).toLowerCase();
  switch (ext) {
    case '.html': return 'text/html; charset=utf-8';
    case '.css': return 'text/css; charset=utf-8';
    case '.js': return 'application/javascript; charset=utf-8';
    case '.json': return 'application/json; charset=utf-8';
    case '.png': return 'image/png';
    case '.jpg':
    case '.jpeg': return 'image/jpeg';
    case '.svg': return 'image/svg+xml';
    case '.wav': return 'audio/wav';
    case '.ico': return 'image/x-icon';
    default: return 'application/octet-stream';
  }
}

function scanDir(dir, baseDir = dir) {
  let results = [];
  const list = fs.readdirSync(dir);
  for (const file of list) {
    const fullPath = path.join(dir, file);
    const stat = fs.statSync(fullPath);
    if (stat.isDirectory()) {
      results = results.concat(scanDir(fullPath, baseDir));
    } else {
      const relPath = path.relative(baseDir, fullPath).replace(/\\/g, '/');
      results.push({ fullPath, relPath });
    }
  }
  return results;
}

const allFiles = scanDir(distDir);
const filesMap = {};
let htmlContent = '';

for (const { fullPath, relPath } of allFiles) {
  const contentType = getContentType(fullPath);
  const isBinary = !contentType.startsWith('text/') && !contentType.startsWith('application/javascript') && !contentType.startsWith('application/json');
  
  if (relPath === 'index.html') {
    htmlContent = fs.readFileSync(fullPath, 'utf8');
  } else {
    if (isBinary) {
      filesMap[relPath] = {
        contentType,
        isBase64: true,
        content: fs.readFileSync(fullPath).toString('base64'),
      };
    } else {
      filesMap[relPath] = {
        contentType,
        isBase64: false,
        content: fs.readFileSync(fullPath, 'utf8'),
      };
    }
  }
}

const outputContent = `// Auto-generated by scripts/generateEmbeddedDist.js at build time.
// Provides 100% self-contained frontend in memory so Phusion Passenger
// serves the complete UI even if dist/ was not uploaded to the server.

export interface EmbeddedFile {
  contentType: string;
  isBase64: boolean;
  content: string;
}

export const EMBEDDED_DIST: {
  html: string;
  files: Record<string, EmbeddedFile>;
} = {
  html: ${JSON.stringify(htmlContent)},
  files: ${JSON.stringify(filesMap, null, 2)},
};
`;

fs.writeFileSync(outputFile, outputContent, 'utf8');
console.log(`[generateEmbeddedDist] Embedded ${allFiles.length} frontend assets into ${outputFile}`);
